#!/usr/bin/env node
// Builds per-language bundles for the MineRStatus docs site:
//
//   content/<lang>/ui.js           <- content/<lang>/language.json
//   content/<lang>/wiki/markdown.js <- content/<lang>/wiki/*.md
//
// The wiki and UI text are loaded via <script> tags instead of fetch(),
// because browsers block fetch() on the file:// protocol — plain <script>
// tags work everywhere, so the site renders even when opened straight from
// disk with no server.
//
// Usage:  node docs/build.js
// Run again after editing any language.json or wiki markdown page.

"use strict";

const fs = require("fs");
const path = require("path");

const contentDir = path.join(__dirname, "content");

const langs = fs
  .readdirSync(contentDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name);

for (const lang of langs) {
  const dir = path.join(contentDir, lang);

  // --- UI bundle from language.json ---
  const langJson = path.join(dir, "language.json");
  if (!fs.existsSync(langJson)) {
    console.warn("SKIP " + lang + ": no language.json");
    continue;
  }
  const data = JSON.parse(fs.readFileSync(langJson, "utf8"));
  const code = data.code || lang;

  const uiOut = path.join(dir, "ui.js");
  const uiHeader =
    "/* Generated by docs/build.js - DO NOT EDIT.\n" +
    "   Rebuild after editing content/language.json files:\n" +
    "   node docs/build.js */\n";
  fs.writeFileSync(
    uiOut,
    uiHeader +
      "window.UI = window.UI || {};\n" +
      "window.UI[" +
      JSON.stringify(code) +
      "] = " +
      JSON.stringify(data, null, 2) +
      ";\n",
    "utf8"
  );
  console.log("Wrote " + path.relative(process.cwd(), uiOut));

  // --- Wiki markdown bundle ---
  const wikiDir = path.join(dir, "wiki");
  if (!fs.existsSync(wikiDir)) continue;

  const files = fs
    .readdirSync(wikiDir)
    .filter((f) => f.endsWith(".md") && f !== "markdown.js");

  const pages = {};
  for (const f of files) {
    const key = f.slice(0, -3);
    pages[key] = fs.readFileSync(path.join(wikiDir, f), "utf8");
  }

  const mdOut = path.join(wikiDir, "markdown.js");
  const mdHeader =
    "/* Generated by docs/build.js - DO NOT EDIT.\n" +
    "   Rebuild after editing any wiki markdown page:\n" +
    "   node docs/build.js */\n";
  fs.writeFileSync(
    mdOut,
    mdHeader +
      "window.WIKI_MARKDOWN = window.WIKI_MARKDOWN || {};\n" +
      "window.WIKI_MARKDOWN[" +
      JSON.stringify(code) +
      "] = " +
      JSON.stringify(pages, null, 2) +
      ";\n",
    "utf8"
  );
  console.log("Wrote " + path.relative(process.cwd(), mdOut));
  console.log("  wiki pages: " + Object.keys(pages).join(", "));
}

console.log("Languages: " + langs.join(", "));